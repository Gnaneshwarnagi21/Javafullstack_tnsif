package day2;

public class switchcasecs {
	int day = 1 ;
	public void selectDay() {
		switch(day) {
		case 1: System.out.println("on Monday"); break;
		case 2: System.out.println("on Tuesday"); break;
		case 3: System.out.println("on wednesday"); break;
		case 4: System.out.println("on Thursday"); break;
		case 5: System.out.println("on friday"); break;
		case 6: System.out.println("on saturday"); break;
		case 7: System.out.println("on sunday"); break;
		default: System.out.println("enter valid input");
		
		}
	}

}
